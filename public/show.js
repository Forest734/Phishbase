// The show page, #/show/<id>: the setlist with each song's length, tags and
// the notes on them, then the show's own notes, its photos, and the taper
// notes that came with the recording.
import { JAM_MARK, api, esc, formatDate, formatDay, formatDuration, pageTitle, place, tagNames } from "./lib.js";

// Tags about the recording rather than the playing: they go on the recording
// line, not beside songs.
const RECORDING = new Set(["sbd", "rmstr", "cut"]);

// Plain text, escaped, with its URLs made into links.
const paragraphs = (text) =>
  text
    .split(/(https?:\/\/[^\s<>"']*[^\s<>"'.,;:!?)])/)
    .map((part, i) => (i % 2 ? `<a href="${esc(part)}">${esc(part)}</a>` : esc(part)))
    .join("");

export async function showPage(id) {
  const [s, names] = await Promise.all([api(`shows/${encodeURIComponent(id)}`), tagNames()]);
  if (!s) return `<h2>Show not found</h2>`;
  const tagName = (tag) => names.get(tag) ?? tag;
  const pager = `<p class="pager">
      ${s.prev ? `<a href="#/show/${esc(s.prev)}">← previous show</a>` : "<span></span>"}
      <a href="#/year/${s.year}">${s.year}</a>
      ${s.next ? `<a href="#/show/${esc(s.next)}">next show →</a>` : "<span></span>"}
    </p>`;
  const lede = `<p class="lede"><a href="#/stats?venue=${esc(s.venueId)}">${esc(s.venue)}</a> · ${esc(place(s))}</p>`;
  return `${pager}
    ${pageTitle(`<h2>${esc(formatDate(s.date))}</h2>`, lede)}
    <div class="show-head">
      ${s.cover ? `<figure class="cover"><img src="${esc(s.cover)}" width="256" height="256" alt="Cover art for this show">
        <figcaption>Cover art generated by <a href="${esc(s.listen ?? "https://phish.in")}">phish.in</a></figcaption></figure>` : ""}
      ${facts(s, tagName)}
    </div>
    ${setlist(s, tagName)}
    ${showNotes(s, tagName)}
    ${gallery(s)}
    ${s.taperNotes ? `<details class="card taper"><summary>Taper notes</summary><pre>${paragraphs(s.taperNotes)}</pre></details>` : ""}`;
}

function facts(s, tagName) {
  const rows = [];
  if (s.tour) rows.push(["Tour", `<a href="#/shows?tour=${esc(s.tour)}">${esc(s.tourName)}</a>`]);
  if (s.songCount) rows.push(["Setlist", `${s.songCount} songs in ${s.sets.length} ${s.sets.length === 1 ? "set" : "sets"}`]);
  if (s.audio === "missing") {
    rows.push(["Recording", "None on phish.in"]);
  } else {
    const kind = [
      s.duration ? formatDuration(s.duration) : "",
      s.audio === "partial" ? "partial" : "",
      ...s.tags.filter((t) => RECORDING.has(t)).map((t) => `<a href="#/shows?tag=${esc(t)}">${esc(tagName(t).toLowerCase())}</a>`),
    ].filter(Boolean);
    rows.push(["Recording", `${kind.length ? `${kind.join(", ")} · ` : ""}<a href="${esc(s.listen)}">Listen on phish.in</a>`]);
  }
  // A button, not an href="#photos", which the hash router would take for a page.
  if (s.photos) rows.push(["Photos", `<button type="button" class="link" data-jump="#photos">${s.photos} ${s.photos === 1 ? "photo" : "photos"} ↓</button>`]);
  return `<dl class="facts">${rows.map(([k, v]) => `<dt>${k}</dt><dd>${v}</dd>`).join("")}</dl>`;
}

function setlist(s, tagName) {
  if (!s.sets.length) return `<p class="muted">No setlist is recorded for this show.</p>`;
  const track = (song) => {
    const noted = new Set(song.notes.map((n) => n.tag));
    const chips = song.tags
      .filter((t) => !RECORDING.has(t) && t !== "jamcharts" && !noted.has(t))
      .map((t) => `<a class="tag" href="#/shows?tag=${esc(t)}">${esc(tagName(t))}</a>`);
    const also = song.also.length
      ? `<span class="also">with ${song.also.map((a) => `<a href="#/song/${esc(a.slug)}">${esc(a.name)}</a>`).join(", ")}</span>`
      : "";
    const notes = song.notes
      .filter((n) => !RECORDING.has(n.tag))
      .map((n) => {
        const at = n.at != null ? ` <span class="muted">at ${formatDuration(n.at)}</span>` : "";
        const text = n.notes ? ` ${paragraphs(n.notes)}` : "";
        return `<li><a class="note-tag" href="#/shows?tag=${esc(n.tag)}">${esc(tagName(n.tag))}</a>${text}${at}</li>`;
      });
    return `<li>
        <div class="track">
          <span class="title"><a href="#/song/${esc(song.slug)}">${esc(song.name)}</a>${song.tags.includes("jamcharts") ? JAM_MARK : ""}${also}${chips.join("")}</span>
          <span class="dur">${song.duration ? formatDuration(song.duration) : ""}</span>
        </div>
        ${notes.length ? `<ul class="track-notes">${notes.join("")}</ul>` : ""}
      </li>`;
  };
  return `<div class="sets">${s.sets
    .map((set) => `<section class="set"><h3>${esc(set.label)}</h3><ol>${set.songs.map(track).join("")}</ol></section>`)
    .join("")}</div>
    <p class="muted note">★ Phish.net Jam Charts pick. Click a tag for every show with it.</p>`;
}

function showNotes(s, tagName) {
  const items = s.tagNotes
    .filter((n) => !RECORDING.has(n.tag))
    .map((n) => `<p><a class="note-tag" href="#/shows?tag=${esc(n.tag)}">${esc(tagName(n.tag))}</a> ${paragraphs(n.notes)}</p>`);
  if (s.notes) items.push(`<p>${paragraphs(s.notes)}</p>`);
  return items.length ? `<section class="card show-notes"><h3>Show notes</h3>${items.join("")}</section>` : "";
}

// Photos taken at this show, then any from a run of shows that includes it,
// where the source doesn't say which night.
function gallery(s) {
  if (!s.gallery.length) return "";
  // Alt text from the show, not Commons' descriptions, which can misdate a photo.
  const figure = (p) => `<figure>
      <a href="${esc(p.page)}"><img src="${esc(p.thumb)}" width="${p.width}" height="${p.height}" loading="lazy" alt="${esc(`Photo by ${p.author} at ${s.venue}`)}"></a>
      <figcaption>${esc(p.author)} · ${p.licenseUrl ? `<a href="${esc(p.licenseUrl)}">${esc(p.license)}</a>` : esc(p.license)}</figcaption>
    </figure>`;
  const night = s.gallery.filter((p) => p.run.length === 1);
  const runs = new Map();
  for (const p of s.gallery.filter((p) => p.run.length > 1)) {
    const key = p.run.join();
    if (!runs.has(key)) runs.set(key, []);
    runs.get(key).push(p);
  }
  const sections = [];
  if (night.length) sections.push(`<div class="photos">${night.map(figure).join("")}</div>`);
  for (const photos of runs.values()) {
    const run = photos[0].run;
    sections.push(`<p class="muted">From the ${run.length} shows here, ${esc(formatDay(run[0]))} to ${esc(formatDay(run.at(-1)))}. The source doesn’t say which night.</p>
      <div class="photos">${photos.map(figure).join("")}</div>`);
  }
  return `<section class="gallery" id="photos">
      <h3 class="section">Photos</h3>
      ${sections.join("")}
      <p class="muted note">From Wikimedia Commons. Click a photo for the full image and its licence.</p>
    </section>`;
}
